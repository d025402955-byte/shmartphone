DIGITS = ['אֶפֶס', 'אַחַת', 'שְׁתַּיִם', 'שָׁלוֹשׁ', 'אַרְבַּע', 'חָמֵשׁ', 'שֵׁשׁ', 'שֶׁבַע', 'שְׁמוֹנֶה', 'תֵּשַׁע']

IVR.update({f'press_{d}': f'הַקִּישׁוּ {d}.' for d in range(10)})


def _words(text):
    import re
    return re.sub(r'(?<![\d{])\b(\d)\b(?![\d}])', lambda m: DIGITS[int(m.group(1))], text)


IVR = {k: _words(v) for k, v in IVR.items()}
